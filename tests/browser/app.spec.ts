test('rejects notation atomically, cancels a busy search, and verifies the reference', async ({ page }) => {
  await page.goto('/');
  await page.getByRole('textbox', { name: 'Scramble notation' }).fill('R INVALID');
  await page.getByRole('button', { name: 'Apply scramble from solved' }).click();
  await expect(page.locator('#status')).toContainText('Unknown move');
  await expect(page.locator('#cube-state-label')).toHaveText('SOLVED');
  await page.locator('#scramble-length').fill('25');
  await page.getByRole('button', { name: 'Generate scramble' }).click();
  await page.locator('#algorithm').selectOption('ida-zero');
  await page.getByRole('button', { name: 'Solve the cube' }).click();
  await page.getByRole('button', { name: 'Cancel', exact: true }).click();
  await expect(page.locator('#status')).toContainText('cancelled');
  await expect(page.locator('#cube-state-label')).toHaveText('SCRAMBLED');
  await page.locator('#algorithm').selectOption('two-phase');
  await page.getByRole('button', { name: 'Solve the cube' }).click();
  await expect(page.locator('#solution-badge')).toHaveText('VERIFIED · REFERENCE', { timeout: 25_000 });
});
