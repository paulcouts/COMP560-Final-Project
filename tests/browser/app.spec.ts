import { test, expect } from '@playwright/test';
test('production worker solves, verifies, plays, reverses, and invalidates a solution', async ({ page }) => {
  const errors: string[] = []; page.on('pageerror', e => errors.push(e.message));
  await page.goto('/');
  await page.getByRole('button', { name: 'Generate scramble' }).click();
  await expect(page.locator('#cube-state-label')).toHaveText('SCRAMBLED');
  await page.getByRole('button', { name: 'Solve the cube' }).click();
  await expect(page.locator('#solution-badge')).toHaveText('VERIFIED · SHORTEST HTM', { timeout: 20_000 });
  await expect(page.locator('#tree-svg .tree-node').first()).toBeAttached();
  await expect(page.locator('#trace-mode')).toHaveText('RECORDED ACTUAL SEARCH');
  await page.getByRole('button', { name: 'Restart search trace' }).click();
  await expect(page.locator('#trace-detail')).toContainText('Start state');
  await page.getByRole('button', { name: 'Next search event' }).click();
  await expect(page.locator('#trace-count')).toContainText('2 /');
  await page.locator('#solve').scrollIntoViewIfNeeded();
  await page.locator('#speed').selectOption('150');
  await page.getByRole('button', { name: 'Play solution' }).click();
  await expect(page.locator('#cube-state-label')).toHaveText('SOLVED', { timeout: 10_000 });
  await expect(page.locator('#move-explanation')).toContainText('every cubie is in its solved position');
  await page.locator('#move-audit summary').click();
  await expect(page.locator('#move-audit tbody tr').last()).toContainText('Solved');
  await expect(page.locator('#next')).toBeDisabled();
  await page.getByRole('button', { name: 'Previous solution move' }).click();
  await expect(page.locator('#cube-state-label')).toHaveText('SCRAMBLED');
  await page.getByRole('button', { name: 'Next solution move' }).click();
  await expect(page.locator('#cube-state-label')).toHaveText('SOLVED');
  await page.getByRole('button', { name: 'Return to solution start' }).click();
  await expect(page.locator('#step-label')).toContainText('0 /');
  await page.getByRole('button', { name: 'Reset to solved' }).click();
  await expect(page.locator('#solution-badge')).toHaveText('WAITING FOR A SOLUTION');
  expect(errors).toEqual([]);
});
