import { chromium } from '@playwright/test';
import { mkdir, copyFile } from 'node:fs/promises';
await mkdir('presentation/assets', { recursive: true });
await mkdir('.cache/demo-recording', { recursive: true });
const browser = await chromium.launch({ args: ['--enable-unsafe-swiftshader'] });
const context = await browser.newContext({ viewport: { width: 1440, height: 1050 },
  recordVideo: { dir: '.cache/demo-recording', size: { width: 1440, height: 1050 } } });
const page = await context.newPage();
await page.goto(process.env.DEMO_URL || 'http://127.0.0.1:5173/');
await page.waitForLoadState('networkidle');
await page.screenshot({ path: 'presentation/assets/playground.png', fullPage: true });
await page.waitForTimeout(1400);
await page.getByRole('button', { name: 'Generate scramble' }).click();
await page.waitForTimeout(1500);
await page.getByRole('button', { name: 'Solve the cube' }).click();
await page.locator('#solution-badge').filter({ hasText: 'VERIFIED' }).waitFor();
await page.locator('.lab-grid').screenshot({ path: 'presentation/assets/lab.png' });
await page.locator('#search-tree').scrollIntoViewIfNeeded();
await page.getByRole('button', { name: 'Restart search trace' }).click();
await page.getByRole('button', { name: 'Play search trace' }).click();
await page.waitForTimeout(3500);
await page.getByRole('button', { name: 'Play search trace' }).click();
await page.locator('#search-tree').screenshot({ path: 'presentation/assets/search-tree.png' });
await page.locator('.solution-panel').scrollIntoViewIfNeeded();
await page.locator('#move-audit summary').click();
await page.waitForTimeout(1500);
await page.getByRole('button', { name: 'Play solution' }).click();
await page.waitForFunction(() => document.getElementById('cube-state-label').textContent === 'SOLVED');
await page.locator('#move-audit').scrollIntoViewIfNeeded();
await page.waitForTimeout(1700);
await page.getByRole('button', { name: 'Previous solution move' }).click();
await page.waitForTimeout(1200);
await page.getByRole('button', { name: 'Next solution move' }).click();
await page.waitForTimeout(1200);
await page.getByRole('button', { name: 'Results', exact: true }).click();
await page.waitForTimeout(3500);
await page.screenshot({ path: 'presentation/assets/experiments.png', fullPage: true });
await context.close();
const video = await page.video().path();
await copyFile(video, 'presentation/demo.webm');
await browser.close();
console.log('Captured presentation/demo.webm and screenshots. Recording has no narration; use the speaker notes.');
